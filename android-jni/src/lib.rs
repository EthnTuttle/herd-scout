use jni::objects::{JByteArray, JClass, JString};
use jni::sys::{jboolean, jint, jlong};
use jni::{JNIEnv, JavaVM};
use moq_media::codec::VideoCodec;
use moq_media::format::{VideoFrame, VideoPreset};
use moq_media::publish::{LocalBroadcast, VideoInput};
use moq_media_android::camera::{CameraFrameSource, SharedCameraSource};
use moq_media_android::handle;
use rusty_codecs::format::Nv12Planes;
