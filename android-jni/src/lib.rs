//! JNI bridge for the herd-scout Android camera publisher.
//!
//! This is the "phone bolted to anything" side of the herd-scout MVP. The
//! Android app captures camera frames via CameraX (NV12 from
//! `ImageAnalysis.OUTPUT_IMAGE_FORMAT_YUV_420_888`), pushes them across the
//! JNI boundary into a [`CameraFrameSource`], and the Rust side hardware
//! encodes H.264 via Android `MediaCodec` (through `moq-media-android`) and
//! publishes a moq broadcast through `iroh-live`.
//!
//! The desktop side subscribes to the broadcast using the same ticket the
//! phone scanned. Tickets are generated by the desktop side and shown as a
//! QR code; the phone scans, parses, and connects.
//!
//! Threading model:
//!   * `JNI_OnLoad` initializes ndk-context (so `oboe`/`MediaCodec` can find
//!     the JavaVM) and a global tokio multi-thread runtime.
//!   * `connectWithTicket` parses the ticket, binds the iroh endpoint, and
//!     stores all session state in an `Arc<Mutex<SessionHandle>>`. The Arc is
//!     leaked into a `jlong` via [`moq_media_android::handle`].
//!   * `startStreaming` constructs a [`LocalBroadcast`] with a
//!     [`CameraFrameSource`] as its video input and calls `Live::publish`.
//!     The encoder pipeline runs on its own tokio task.
//!   * Camera callback thread (CameraX `ImageAnalysis` analyzer executor) calls
//!     `pushCameraNv12` which briefly locks the session, pushes the frame into
//!     the `CameraFrameSource`, and returns. The encoder picks frames off
//!     asynchronously.
//!   * `disconnect` calls `take_handle` (consuming the Arc), shuts down the
//!     `Live` via the runtime, and returns.

#![cfg(target_os = "android")]

